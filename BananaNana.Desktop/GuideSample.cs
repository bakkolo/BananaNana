using SkiaSharp;
namespace BananaNana.Desktop;

// The sample guide behind --guide-maker-sample, used to check the guide view: two steps, the first with a
// generated 800 x 450 PNG (a solid colour with a white rectangle). It is made once; later calls open the same guide.
public static class GuideSample
{
    public const string Title = "Sample guide";
    const int Width = 800, Height = 450;

    // Returns the id of the guide titled Sample guide, creating it when no guide has that title.
    public static Guid EnsureSample(GuideStore store)
    {
        var existing = store.List().FirstOrDefault(g => g.Title == Title);
        if (existing is not null) return existing.Id;

        var doc = store.Create(Title);
        doc.Intro = "Made by --guide-maker-sample to check the guide view.";
        doc.Steps.Add(new GuideStep
        {
            Id = Guid.NewGuid(),
            Title = "Open the window",
            Text = "A solid colour with a white box, generated by the app.",
            Image = Picture(),
            ImageType = "png",
        });
        doc.Steps.Add(new GuideStep { Id = Guid.NewGuid(), Title = "Save", Text = "A step without a picture." });
        store.Save(doc);
        return doc.Id;
    }

    static string Picture()
    {
        using var bitmap = new SKBitmap(Width, Height);
        bitmap.Erase(new SKColor(0x2E, 0x6F, 0xB7));
        using (var canvas = new SKCanvas(bitmap))
        using (var paint = new SKPaint { Color = SKColors.White, IsAntialias = false })
        {
            canvas.DrawRect(SKRect.Create(200, 100, 400, 250), paint);
        }
        using var image = SKImage.FromBitmap(bitmap);
        using var png = image.Encode(SKEncodedImageFormat.Png, 100);
        return Convert.ToBase64String(png.ToArray());
    }
}
